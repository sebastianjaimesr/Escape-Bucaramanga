def text_width(text, spacing=1):
    return max(0, len(text) * (5 + spacing) - spacing)


def draw_text(img, x, y, text, color, scale=1, spacing=1):
    """Dibuja texto pixelado sobre una imagen PIL en modo RGBA."""
    px = img.load()
    w, h = img.size
    cx = x
    for ch in text.upper():
        glyph = GLYPHS.get(ch, GLYPHS["?"])
        for gy, row in enumerate(glyph):
            for gx, bit in enumerate(row):
                if bit != "1":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        X = cx + gx * scale + sx
                        Y = y + gy * scale + sy
                        if 0 <= X < w and 0 <= Y < h:
                            px[X, Y] = color
        cx += (5 + spacing) * scale
    return cx
